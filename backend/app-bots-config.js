// ============================================
// Inference model (owner-chosen + prod-validated — card_6d0f2746 / card_12e6d33b)
//
// Replies are NOT generated by a server-side LLM call (prod has no
// ANTHROPIC_API_KEY → 502) and NOT by a custom async inference entity. Instead,
// each app install binds a FREE official MiniMax bot to its OWN device (slot 1)
// during onboarding. The gateway injects a server-side persona pre-prompt and
// relays the user's message to that bound bot via the normal client-speak
// delivery path; the bot replies `toUser` and the app reads it via
// GET /api/client/pending. No custom job/callback envelope is needed — the
// persona and quota stay entirely server-side.
// ============================================

/**
 * Resolve an (appId, personaId) pair to its server-side config.
 * Returns { app, persona } or null when either the app or the persona is
 * unknown. The caller must NOT disclose which of the two was wrong (avoid
 * leaking the valid appId/persona namespace to probing clients).
 *
 * @param {string} appId
 * @param {string} personaId
 * @returns {{ app: object, persona: object } | null}
 */
function getPersona(appId, personaId) {
    const app = APP_BOTS[appId];
    if (!app) return null;
    const persona = app.personas && app.personas[personaId];
    if (!persona) return null;
    return { app, persona };
}

