'use strict';

// Turns the approved campaign files into everything that is published or handed out:
//   backend/public/AiHankApps/gift-campaigns.js   data the portfolio sidebar renders
//   backend/public/AiHankApps/index.html          cache-busting token for that data file
//   tools/aihankapps-gifts/promo/<id>.md          ready-to-post announcement copy
// The same function serves `build` (write) and `build --check` (compare), so CI can prove the
// published files match the campaign files.
const fs = require('fs');
const path = require('path');
const { LOCALES, TEXT, receiptLine, pendingLine, endedLine } = require('./copy');
const { PUBLIC_DIR, PROMO_DIR, sha256 } = require('./store');
const { formatTaipei, toMs } = require('./time');

const PORTFOLIO_URL = 'https://eclawbot.com/AiHankApps/';
const DATA_FILE = 'gift-campaigns.js';
const DATA_TOKEN = /gift-campaigns\.js\?v=[A-Za-z0-9._-]+/g;

// The newest verified receipt for each game.
function latestReceipts(campaign) {
  const latest = new Map();
  for (const receipt of campaign.receipts || []) {
    const previous = latest.get(receipt.gameId);
    if (!previous || toMs(receipt.verifiedAt) >= toMs(previous.verifiedAt)) latest.set(receipt.gameId, receipt);
  }
  return latest;
}

function gameLines(campaign, locale) {
  return campaign.copy[locale].games.map(game => (game.value ? `${game.line}${TEXT[locale].gap}${game.value}` : game.line));
}

function publicHoliday(campaign) {
  const receipts = latestReceipts(campaign);
  const total = receipts.size ? [...receipts.values()].reduce((sum, receipt) => sum + receipt.mails, 0) : null;
  const copy = {};
  for (const locale of LOCALES) {
    const source = campaign.copy[locale];
    const lines = gameLines(campaign, locale);
    const verified = source.games.filter(game => receipts.has(game.gameId))
      .map(game => receiptLine(locale, game.name, receipts.get(game.gameId)));
    copy[locale] = {
      title: source.title,
      upcoming: [source.intro, ...lines, source.eligibility, source.starts, source.deadline],
      active: [source.intro, ...lines, source.eligibility, source.deadline, ...(verified.length ? verified : [pendingLine(locale)])],
      ended: endedLine(locale, campaign, total)
    };
  }
  return {
    id: campaign.id,
    kind: 'holiday',
    apps: campaign.games.map(entry => entry.gameId),
    announceAt: campaign.announceAt,
    startsAt: campaign.startsAt,
    claimEndsAt: campaign.claimEndsAt,
    copy
  };
}

// Campaigns from before this tool keep their original record and wording.
function publicLegacy(campaign) {
  const result = {
    id: campaign.id,
    kind: 'legacy',
    apps: [campaign.appId],
    ...(campaign.startsAt ? { announceAt: campaign.startsAt, startsAt: campaign.startsAt } : {}),
    claimEndsAt: campaign.claimEndsAt,
    record: campaign.record || {}
  };
  if (campaign.copy && campaign.startsAt) {
    const issued = campaign.record && Number.isSafeInteger(campaign.record.issuedCount) ? campaign.record.issuedCount : null;
    result.copy = {};
    for (const locale of LOCALES) {
      const source = campaign.copy[locale];
      result.copy[locale] = { title: source.title, upcoming: source.lines, active: source.lines, ended: endedLine(locale, campaign, issued) };
    }
  }
  return result;
}

// Newest first. Drafts and cancelled campaigns are never published.
function buildPublicData(campaigns) {
  return campaigns.filter(campaign => campaign.status === 'approved')
    .map(campaign => (campaign.kind === 'legacy' ? publicLegacy(campaign) : publicHoliday(campaign)))
    .sort((a, b) => toMs(b.startsAt || b.claimEndsAt) - toMs(a.startsAt || a.claimEndsAt));
}

function renderDataFile(data) {
  const json = JSON.stringify(data, null, 2).replace(/\n/g, '\n  ');
  return [
    '// Generated by tools/aihankapps-gifts (node tools/aihankapps-gifts/cli.js build).',
    '// Do not edit by hand: change the campaign files and rebuild. Only approved campaigns are',
    '// published here; drafts stay out of public assets.',
    '(() => {',
    "  'use strict';",
    '  const freeze = value => {',
    "    if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); }",
    '    return value;',
    '  };',
    `  window.AIHANK_GIFT_CAMPAIGNS = freeze(${json});`,
    '})();',
    ''
  ].join('\n');
}

// index.html loads the data file with a content-hash token so a new campaign is never hidden
// behind the ten-minute script cache.
function syncIndexHtml(html, dataFile) {
  const matches = html.match(DATA_TOKEN) || [];
  if (matches.length !== 1) throw new Error(`index_html_data_token_count:${matches.length}`);
  return html.replace(DATA_TOKEN, `${DATA_FILE}?v=${sha256(dataFile).slice(0, 12)}`);
}

function socialPost(campaign, locale) {
  const copy = campaign.copy[locale];
  return [
    `【${copy.title}】`,
    copy.intro,
    ...gameLines(campaign, locale),
    copy.eligibility,
    copy.deadline,
    `${PORTFOLIO_URL}#${campaign.id}`
  ].join('\n');
}

function devlog(campaign, entry, game) {
  const paragraph = locale => {
    const copy = campaign.copy[locale];
    const line = gameLines(campaign, locale)[campaign.games.indexOf(entry)];
    return [copy.intro, line, copy.eligibility, copy.deadline].join(TEXT[locale].gap || '');
  };
  return [
    `### ${game.names['zh-TW']}`,
    '',
    `頁面：${game.links.itch}`,
    '',
    `標題：${campaign.copy['zh-TW'].title}｜${campaign.copy.en.title}`,
    '',
    '內文：',
    '',
    paragraph('zh-TW'),
    '',
    paragraph('en'),
    '',
    `${PORTFOLIO_URL}#${campaign.id}`
  ].join('\n');
}

// One Markdown file per campaign with every outward-facing text, ready to paste.
function promoMarkdown(campaign, games) {
  const gameOf = entry => games.games.find(game => game.id === entry.gameId);
  const localeNames = { 'zh-TW': '繁體中文', 'zh-CN': '简体中文', en: 'English', ja: '日本語', ko: '한국어' };
  const sections = [
    `# ${campaign.copy['zh-TW'].title}｜對外宣傳文案`,
    '',
    '由 `tools/aihankapps-gifts` 依活動檔產生，內容與作品集公告、遊戲內信件一致；要改文案請改活動檔後重新 build，不要直接改這份。',
    '',
    `- 活動公告：${PORTFOLIO_URL}#${campaign.id}`,
    `- 作品集開始顯示：${formatTaipei(campaign.announceAt)}（台北時間）`,
    `- 開始寄送：${formatTaipei(campaign.startsAt)}`,
    `- 寄送期結束：${formatTaipei(campaign.deliveryEndsAt)}`,
    `- 領取截止：${formatTaipei(campaign.claimEndsAt)}`,
    '',
    '## 社群貼文'
  ];
  for (const locale of LOCALES) sections.push('', `### ${localeNames[locale]}`, '', '```text', socialPost(campaign, locale), '```');
  sections.push('', '## itch.io devlog');
  for (const entry of campaign.games) {
    const game = gameOf(entry);
    if (game.links && game.links.itch) sections.push('', devlog(campaign, entry, game));
  }
  sections.push('', '## 遊戲內信件（核准時已凍結，寄送時逐字使用）');
  for (const entry of campaign.games) {
    sections.push('', `### ${gameOf(entry).names['zh-TW']}`, '', `主旨：${entry.mail.subject}`, '', '```text', entry.mail.body, '```');
  }
  return sections.join('\n') + '\n';
}

// Every generated file as { absolutePath: content }.
function outputs(campaigns, games, { publicDir = PUBLIC_DIR, promoDir = PROMO_DIR } = {}) {
  const dataFile = renderDataFile(buildPublicData(campaigns));
  const indexPath = path.join(publicDir, 'index.html');
  const files = {
    [path.join(publicDir, DATA_FILE)]: dataFile,
    [indexPath]: syncIndexHtml(fs.readFileSync(indexPath, 'utf8'), dataFile)
  };
  for (const campaign of campaigns) {
    if (campaign.kind === 'holiday' && campaign.status === 'approved') {
      files[path.join(promoDir, `${campaign.id}.md`)] = promoMarkdown(campaign, games);
    }
  }
  return files;
}

// Promo files left behind by a campaign that was cancelled or removed.
function obsolete(files, { promoDir = PROMO_DIR } = {}) {
  if (!fs.existsSync(promoDir)) return [];
  return fs.readdirSync(promoDir).filter(name => name.endsWith('.md'))
    .map(name => path.join(promoDir, name)).filter(file => !(file in files));
}

// Files whose content on disk differs from what the campaign files generate.
function stale(files, options) {
  return Object.entries(files)
    .filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content)
    .map(([file]) => file).concat(obsolete(files, options));
}

function write(files, options) {
  const removed = obsolete(files, options);
  const changed = stale(files, options).filter(file => !removed.includes(file));
  for (const file of changed) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, files[file]);
  }
  for (const file of removed) fs.unlinkSync(file);
  return { written: changed, removed };
}

module.exports = {
  PORTFOLIO_URL, DATA_FILE, latestReceipts, buildPublicData, renderDataFile, syncIndexHtml,
  socialPost, promoMarkdown, outputs, obsolete, stale, write
};
